//FOR-PARA
/*
O FOR é utilizado quando sabemos quantas vezes precisamos repetir uma ação

ESTRUTURA:
*for(inicio;condição;incremento){
    console.log

}

Ofor possui tres partes

1.Inicio: criar contador
2.Condição: determina ate quando repetir
3.Incremento:atualiza o contador
*****ATENÇAÕ*****
Precisamos utilizar o ; para separar essas partes

*/
for (let i =1; i <=5; i++){
    console.log("Contagem", i)
}

//ENTENDENDO
//let i = 1 ->começa em 1 
//i<= 5 -> repete enquanto i for ate 5
//i++ -> aumenta 1 apos cada repetição