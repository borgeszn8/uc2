// SWITCH CASE

// O switch e usado quando temos Varias opsoes e queremos executar uma acao dependendo do valor

//---------------------------------------------------------------------------------------------------------

let opcao = 8

switch(opcao)
{
    case 1: 
        console.log(" Opsao 1 ")
        break
    case 2:
        console.log("opcao 2")
        break
    case 3:
        console.log("opsao 3")
        break
    default:
        console.log("Opsao invalida")
}